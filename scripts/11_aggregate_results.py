#!/usr/bin/env python
"""Aggregate the results of all evaluated models into comparison tables.

Reads `<RESULTS_DIR>/metrics/ctx{N}/json/*.json` (custom models + baselines, generated by
`scripts/10_evaluate.py`) and writes one comparison table per metric family:
- `<RESULTS_DIR>/comparison_point.csv` -- point forecast (MAE/sMAPE/MASE): Unimodal-ablation,
  NeuroSym-CBF, AutoETS, Chronos-Bolt, Chronos-2, TimesFM.
- `<RESULTS_DIR>/comparison_probabilistic.csv` -- pinball/coverage/width: only if there are
    results for NeuroSym-CBF (pinball) / Chronos-2 (pinball) (`experimental/`, see README).

Usage:
    python scripts/11_aggregate_results.py
"""
from __future__ import annotations

import argparse
import logging

from fred_forecast.config import results_dir
from fred_forecast.evaluation.aggregate_results import build_comparison_tables, load_all_results

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)


def main() -> None:
    argparse.ArgumentParser(description=__doc__).parse_args()  # only for -h/--help

    metrics_dir = results_dir() / "metrics"
    results = load_all_results(metrics_dir)
    logger.info("Results found in %s: %d", metrics_dir, len(results))

    point_df, prob_df = build_comparison_tables(results)
    out_dir = results_dir()

    if not point_df.empty:
        point_path = out_dir / "comparison_point.csv"
        point_df.to_csv(point_path, index=False)
        logger.info("Comparison table (point forecast) -> %s", point_path)
        print(point_df.to_string(index=False))
    else:
        logger.warning("No point-forecast results yet (field 'mae_mean').")

    if not prob_df.empty:
        prob_path = out_dir / "comparison_probabilistic.csv"
        prob_df.to_csv(prob_path, index=False)
        logger.info("Comparison table (probabilistic) -> %s", prob_path)
        print(prob_df.to_string(index=False))
    else:
        logger.info("No probabilistic results (NeuroSym-CBF/Chronos-2 pinball are experimental work, see experimental/README.md).")


if __name__ == "__main__":
    main()
