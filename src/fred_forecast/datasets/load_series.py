"""Load series and metadata embeddings for training/evaluation of the custom model.

Reads the database built in Phase 3 (`build_database.py`, JSON) and the metadata embeddings from
Phase 4 (`text_encoder.py`, pickle) -- only the fields needed by `TimeSeriesDataset`:
`series_id`/`observations` and `series_id`/`embeddings`, respectively.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd


def load_series_observations(database_json_path: Path) -> pd.DataFrame:
    """DataFrame with columns `series_id`, `observations` (np.float32 arrays), from
    the JSON database generated by `build_database.py`.
    """
    with open(database_json_path) as f:
        data = json.load(f)

    rows = [
        {"series_id": str(x["series_id"]), "observations": np.asarray(x["observations"], dtype=np.float32)}
        for x in data
        if "series_id" in x
    ]
    return pd.DataFrame(rows)


def load_metadata_embeddings(embeddings_pkl_path: Path) -> pd.DataFrame:
    """DataFrame indexed by `series_id`, with an `embeddings` column (np.float32 arrays), from
    the pickle generated by `text_encoder.build_metadata_embeddings`.
    """
    metadata_df = pd.read_pickle(embeddings_pkl_path)
    metadata_df["series_id"] = metadata_df["series_id"].astype(str)
    metadata_df["embeddings"] = metadata_df["embeddings"].apply(lambda x: np.asarray(x, dtype=np.float32))
    return metadata_df.set_index("series_id")
